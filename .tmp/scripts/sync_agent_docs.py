#!/usr/bin/env python3
"""Keep the per-tool agent entry points in sync with the canonical harness in `.github/`.

Single source of truth
----------------------
- `AGENTS.md`                     — the operating instructions (all tools read this)
- `.github/skills/*/SKILL.md`     — the skills themselves

Generated pointers (never edit by hand)
---------------------------------------
- `.claude/skills/<name>/SKILL.md` — thin proxies so Claude Code's Skill tool can
  discover and invoke the same skills that live under `.github/skills/`.

Usage
-----
    python .tmp/scripts/sync_agent_docs.py            # write/refresh proxies
    python .tmp/scripts/sync_agent_docs.py --check    # exit 1 if out of date (CI gate)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE_SKILLS = REPO / ".github" / "skills"
PROXY_SKILLS = REPO / ".claude" / "skills"

BANNER = "<!-- GENERATED by .tmp/scripts/sync_agent_docs.py — do not edit. -->"


def parse_frontmatter(text: str) -> dict[str, str]:
    """Minimal YAML front-matter reader: `key: value` and folded `key: >` blocks."""
    if not text.startswith("---"):
        return {}
    lines = text.splitlines()
    try:
        end = next(i for i, ln in enumerate(lines[1:], start=1) if ln.strip() == "---")
    except StopIteration:
        return {}

    meta: dict[str, list[str]] = {}
    key: str | None = None
    for raw in lines[1:end]:
        if raw[:1] not in (" ", "\t") and ":" in raw:
            key, _, value = raw.partition(":")
            key = key.strip()
            value = value.strip()
            meta[key] = [] if value in (">", "|", ">-", "|-") else [value]
        elif key and raw.strip():
            meta[key].append(raw.strip())
    return {k: _unquote(" ".join(v).strip()) for k, v in meta.items()}


def _unquote(value: str) -> str:
    """Undo the quoting emitted by `yaml_quote` (and plain double-quoted scalars)."""
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1]
    return value


def skill_metadata(skill_dir: Path) -> dict[str, str]:
    """name/description for a skill, falling back to the first prose paragraph."""
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    meta = parse_frontmatter(text)
    name = meta.get("name") or skill_dir.name
    description = meta.get("description", "")
    if not description:
        body = text.split("---", 2)[-1] if text.startswith("---") else text
        para: list[str] = []
        for line in body.splitlines():
            if line.startswith("#"):
                continue
            if not line.strip():
                if para:
                    break
                continue
            para.append(line.strip())
        description = " ".join(para)
    return {"name": name, "description": " ".join(description.split())}


def yaml_quote(value: str) -> str:
    """Single-quoted YAML scalar.

    Descriptions routinely contain ': ' ("Analysis with CalculiX (ccx): steady ...") and
    double quotes ('Use for "run the CFD"'), both of which break an unquoted plain scalar
    and silently corrupt the parsed front-matter. Single quotes only need doubling.
    """
    return "'" + value.replace("'", "''") + "'"


def proxy_text(meta: dict[str, str], skill_dir: Path) -> str:
    rel = skill_dir.relative_to(REPO).as_posix()
    return f"""---
name: {meta['name']}
description: {yaml_quote(meta['description'])}
---
{BANNER}

# {meta['name']} (proxy)

The canonical skill lives in the shared harness so that GitHub Copilot, Copilot Chat,
Claude Code, and any other AGENTS.md-aware tool run the *same* instructions.

**Read `{rel}/SKILL.md` now and follow it.**

- Scripts: `{rel}/scripts/`
- Run them from the repo root with the venv Python, passing nested study slugs
  (`--study <project>/<study>`).
- Workspace-wide rules: `AGENTS.md` (and `CLAUDE.md` for the Claude-specific notes).
"""


def sync(check: bool) -> int:
    if not SOURCE_SKILLS.is_dir():
        print(f"no skills directory at {SOURCE_SKILLS}", file=sys.stderr)
        return 1

    skill_dirs = sorted(d for d in SOURCE_SKILLS.iterdir() if (d / "SKILL.md").is_file())
    expected = {d.name for d in skill_dirs}
    stale: list[str] = []

    for skill_dir in skill_dirs:
        target = PROXY_SKILLS / skill_dir.name / "SKILL.md"
        wanted = proxy_text(skill_metadata(skill_dir), skill_dir)
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == wanted:
            continue
        if check:
            state = "out of date" if current else "missing"
            stale.append(f"{state}: {target.relative_to(REPO).as_posix()}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(wanted, encoding="utf-8")
        print(f"wrote {target.relative_to(REPO).as_posix()}")

    if PROXY_SKILLS.is_dir():
        orphans = [d for d in sorted(PROXY_SKILLS.iterdir())
                   if d.is_dir() and d.name not in expected]
        for orphan in orphans:
            rel = orphan.relative_to(REPO).as_posix()
            if check:
                stale.append(f"orphaned proxy (source skill removed): {rel}")
                continue
            for f in sorted(orphan.rglob("*"), reverse=True):
                if f.is_file():
                    f.unlink()
                else:
                    f.rmdir()
            orphan.rmdir()
            print(f"removed {rel}")

    if stale:
        print("Claude skill proxies are out of sync:", file=sys.stderr)
        for item in stale:
            print(f"  - {item}", file=sys.stderr)
        print("\nRun: python .tmp/scripts/sync_agent_docs.py", file=sys.stderr)
        return 1

    print(f"{len(skill_dirs)} skill proxies in sync" if check else f"synced {len(skill_dirs)} skills")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if regeneration is needed")
    return sync(ap.parse_args().check)


if __name__ == "__main__":
    raise SystemExit(main())
