#!/usr/bin/env python3
"""OpenFOAM case factory — compressibleInterFoam VOF case for submerged exhaust discharge.

Writes a complete transient, compressible, two-phase (exhaust gas / seawater) case:
  * VOF interface capture (MULES), gravity enabled, hydrostatic pressure via p_rgh
  * Ideal-gas multi-component exhaust mixture (frozen composition, JANAF cp(T))
  * Constant-density seawater phase
  * k-omega SST turbulence with wall functions
  * Function objects: inlet back-pressure, jet-axis / plume-rise line samples, probes

Configuration dict keys (all optional, defaults below):
  U_in [m/s], T_exhaust_C, T_water_C, T_air_C, turbulence_intensity,
  end_time_s, write_interval_s, max_co, n_procs, p_atm,
  mole_fractions {N2,O2,CO2,H2O}, geometry {see marine_exhaust_geometry.DEFAULT_PARAMS}
"""
from __future__ import annotations

import json
import math
import re
import shutil
from pathlib import Path

from exhaust_properties import mixture_properties, openfoam_janaf_block, DEFAULT_MOLE_FRACTIONS
from marine_exhaust_geometry import DEFAULT_PARAMS as GEO_DEFAULTS

DEFAULT_CFG = {
    "U_in": 15.0,                 # exhaust velocity [m/s], study range 10-25
    "T_exhaust_C": 400.0,         # exhaust temperature [C], study range 300-550
    "T_water_C": 15.0,
    "T_air_C": 20.0,
    "turbulence_intensity": 0.05,
    "end_time_s": 4.0,
    "write_interval_s": 0.4,
    "max_co": 0.9,
    "n_procs": 6,
    "p_atm": 101325.0,
    "rho_water": 1025.0,          # representative seawater
    "cp_water": 3985.0,
    "mu_water": 1.08e-3,          # at ~15 C (temperature dependence: refinement stage)
    "pr_water": 7.2,
    "sigma": 0.07,                # surface tension gas-water [N/m]
    "mole_fractions": DEFAULT_MOLE_FRACTIONS,
    "geometry": {},
}

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
| Generated by agent-cfd-fea-engineer (DOE Framework)                          |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    {location}object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def _hdr(cls: str, obj: str, location: str = "") -> str:
    loc = f'location    "{location}";\n    ' if location else ""
    return HEADER.format(cls=cls, obj=obj, location=loc)


def _write(case: Path, rel: str, body: str, cls: str = "dictionary") -> None:
    path = case / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    parts = rel.split("/")
    location = "/".join(parts[:-1])
    path.write_text(_hdr(cls, parts[-1], location) + body, encoding="utf-8")


def merged_config(cfg: dict | None) -> dict:
    out = json.loads(json.dumps(DEFAULT_CFG))
    for k, v in (cfg or {}).items():
        if k in ("geometry", "mole_fractions") and isinstance(v, dict):
            out[k].update(v)
        else:
            out[k] = v
    return out


# ─────────────────────────────── field files (0.orig) ────────────────────────

def _field(cls, obj, dims, internal, patches: dict) -> str:
    b = f"dimensions      {dims};\n\ninternalField   {internal};\n\nboundaryField\n{{\n"
    for name, spec in patches.items():
        b += f"    {name}\n    {{\n"
        for k, v in spec.items():
            b += f"        {k:15s} {v};\n"
        b += "    }\n"
    b += "}\n"
    return b


def write_fields(case: Path, cfg: dict) -> None:
    T_exh = cfg["T_exhaust_C"] + 273.15
    T_air = cfg["T_air_C"] + 273.15
    U = cfg["U_in"]
    I = cfg["turbulence_intensity"]
    D = {**GEO_DEFAULTS, **cfg["geometry"]}["pipe_diameter"]
    k_in = max(1.5 * (I * U) ** 2, 1e-4)
    # omega from mixing length ~ 0.07 D
    omega_in = max(math.sqrt(k_in) / (0.09 ** 0.25 * 0.07 * D), 1.0)
    p0 = cfg["p_atm"]
    walls = ("pipeWall", "seaBoundary")

    _write(case, "0.orig/U", _field("volVectorField", "U", "[0 1 -1 0 0 0 0]", "uniform (0 0 0)", {
        "inlet": {"type": "fixedValue", "value": f"uniform ({U} 0 0)"},
        "atmosphere": {"type": "pressureInletOutletVelocity", "value": "uniform (0 0 0)"},
        **{w: {"type": "noSlip"} for w in walls},
    }), "volVectorField")

    _write(case, "0.orig/p_rgh", _field("volScalarField", "p_rgh", "[1 -1 -2 0 0 0 0]", f"uniform {p0}", {
        "inlet": {"type": "fixedFluxPressure", "value": f"uniform {p0}"},
        "atmosphere": {"type": "totalPressure", "p0": f"uniform {p0}", "value": f"uniform {p0}"},
        **{w: {"type": "fixedFluxPressure", "value": f"uniform {p0}"} for w in walls},
    }), "volScalarField")

    _write(case, "0.orig/p", _field("volScalarField", "p", "[1 -1 -2 0 0 0 0]", f"uniform {p0}", {
        n: {"type": "calculated", "value": f"uniform {p0}"}
        for n in ("inlet", "atmosphere", *walls)
    }), "volScalarField")

    _write(case, "0.orig/T", _field("volScalarField", "T", "[0 0 0 1 0 0 0]", f"uniform {T_air}", {
        "inlet": {"type": "fixedValue", "value": f"uniform {T_exh}"},
        "atmosphere": {"type": "inletOutlet", "inletValue": f"uniform {T_air}", "value": f"uniform {T_air}"},
        **{w: {"type": "zeroGradient"} for w in walls},  # thermal wall BC: to be finalised
    }), "volScalarField")

    _write(case, "0.orig/alpha.water", _field("volScalarField", "alpha.water", "[0 0 0 0 0 0 0]", "uniform 0", {
        "inlet": {"type": "fixedValue", "value": "uniform 0"},
        "atmosphere": {"type": "inletOutlet", "inletValue": "uniform 0", "value": "uniform 0"},
        **{w: {"type": "zeroGradient"} for w in walls},
    }), "volScalarField")

    _write(case, "0.orig/k", _field("volScalarField", "k", "[0 2 -2 0 0 0 0]", f"uniform {k_in:.6g}", {
        "inlet": {"type": "turbulentIntensityKineticEnergyInlet", "intensity": f"{I}", "value": f"uniform {k_in:.6g}"},
        "atmosphere": {"type": "inletOutlet", "inletValue": f"uniform {k_in:.6g}", "value": f"uniform {k_in:.6g}"},
        **{w: {"type": "kqRWallFunction", "value": f"uniform {k_in:.6g}"} for w in walls},
    }), "volScalarField")

    _write(case, "0.orig/omega", _field("volScalarField", "omega", "[0 0 -1 0 0 0 0]", f"uniform {omega_in:.6g}", {
        "inlet": {"type": "turbulentMixingLengthFrequencyInlet", "mixingLength": f"{0.07 * D:.4g}",
                  "value": f"uniform {omega_in:.6g}"},
        "atmosphere": {"type": "inletOutlet", "inletValue": f"uniform {omega_in:.6g}", "value": f"uniform {omega_in:.6g}"},
        **{w: {"type": "omegaWallFunction", "value": f"uniform {omega_in:.6g}"} for w in walls},
    }), "volScalarField")

    _write(case, "0.orig/nut", _field("volScalarField", "nut", "[0 2 -1 0 0 0 0]", "uniform 0", {
        "inlet": {"type": "calculated", "value": "uniform 0"},
        "atmosphere": {"type": "calculated", "value": "uniform 0"},
        **{w: {"type": "nutkWallFunction", "value": "uniform 0"} for w in walls},
    }), "volScalarField")

    _write(case, "0.orig/alphat", _field("volScalarField", "alphat", "[1 -1 -1 0 0 0 0]", "uniform 0", {
        "inlet": {"type": "calculated", "value": "uniform 0"},
        "atmosphere": {"type": "calculated", "value": "uniform 0"},
        **{w: {"type": "compressible::alphatWallFunction", "Prt": "0.85", "value": "uniform 0"} for w in walls},
    }), "volScalarField")


# ─────────────────────────────── constant/ ───────────────────────────────────

def write_constant(case: Path, cfg: dict) -> None:
    _write(case, "constant/g",
           'dimensions      [0 1 -2 0 0 0 0];\nvalue           (0 0 -9.81);\n',
           "uniformDimensionedVectorField")

    # water first: the solver reads/solves alpha.<phase1> — we provide alpha.water
    _write(case, "constant/thermophysicalProperties",
           f"phases          (water gas);\n\npMin            10000;\n\nsigma           {cfg['sigma']};\n")

    props = mixture_properties(cfg["mole_fractions"])
    gas_block = openfoam_janaf_block(props)
    _write(case, "constant/thermophysicalProperties.gas", f"""thermoType
{{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       sutherland;
    thermo          janaf;
    equationOfState perfectGas;
    specie          specie;
    energy          sensibleInternalEnergy;
}}

// Representative marine diesel exhaust: frozen multi-component ideal-gas mixture
// {json.dumps(props['composition_mole_fractions'])}
// Mixture molar mass {props['molar_mass_kg_per_kmol']} kg/kmol; cp(400 C) ~ {props['cp_at_400C_J_per_kgK']} J/kg-K
mixture
{{
{gas_block}
}}
""")

    _write(case, "constant/thermophysicalProperties.water", f"""thermoType
{{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState rhoConst;
    specie          specie;
    energy          sensibleInternalEnergy;
}}

mixture
{{
    specie
    {{
        molWeight   18.015;
    }}
    equationOfState
    {{
        rho         {cfg['rho_water']};
    }}
    thermodynamics
    {{
        Cp          {cfg['cp_water']};
        Hf          0;
    }}
    transport
    {{
        mu          {cfg['mu_water']};
        Pr          {cfg['pr_water']};
    }}
}}
""")

    _write(case, "constant/turbulenceProperties", """simulationType  RAS;

RAS
{
    RASModel        kOmegaSST;
    turbulence      on;
    printCoeffs     on;
}
""")


# ─────────────────────────────── system/ ─────────────────────────────────────

def write_system(case: Path, cfg: dict) -> None:
    geo = {**GEO_DEFAULTS, **cfg["geometry"]}
    D = geo["pipe_diameter"]
    Lpen = geo["pipe_penetration"]
    Hs = geo["submergence"]
    Lx = geo["domain_length"]
    T_water = cfg["T_water_C"] + 273.15
    T_exh = cfg["T_exhaust_C"] + 273.15

    axial_end = min(Lpen + 12 * D, Lx * 0.95)
    _write(case, "system/controlDict", f"""application     compressibleInterFoam;

startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {cfg['end_time_s']};
deltaT          1e-05;

writeControl    adjustable;
writeInterval   {cfg['write_interval_s']};
purgeWrite      0;
writeFormat     binary;
writePrecision  7;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable yes;

adjustTimeStep  yes;
maxCo           {cfg['max_co']};
maxAlphaCo      {cfg['max_co']};
maxDeltaT       0.01;

functions
{{
    inletPressure
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            inlet;
        operation       areaAverage;
        fields          (p);
        writeFields     no;
        writeControl    timeStep;
        writeInterval   10;
        log             no;
    }}

    jetSamples
    {{
        type            sets;
        libs            (sampling);
        interpolationScheme cellPoint;
        setFormat       csv;
        writeControl    adjustable;
        writeInterval   {cfg['write_interval_s']};
        fields          (T U p alpha.water);
        sets
        {{
            jetAxis
            {{
                type    uniform;
                axis    x;
                start   ({Lpen + 0.01} 0 {-Hs});
                end     ({axial_end} 0 {-Hs});
                nPoints 200;
            }}
            plumeRise
            {{
                type    uniform;
                axis    z;
                start   ({Lpen + 2 * D} 0 {-Hs});
                end     ({Lpen + 2 * D} 0 0.2);
                nPoints 120;
            }}
        }}
    }}

    probes
    {{
        type            probes;
        libs            (sampling);
        writeControl    timeStep;
        writeInterval   20;
        fields          (p T alpha.water);
        probeLocations
        (
            ({Lpen + 1 * D} 0 {-Hs})
            ({Lpen + 4 * D} 0 {-Hs})
            ({Lpen + 8 * D} 0 {-Hs})
        );
    }}
}}
""")

    _write(case, "system/fvSchemes", """ddtSchemes
{
    default         Euler;
}

gradSchemes
{
    default         Gauss linear;
}

divSchemes
{
    div(rhoPhi,U)   Gauss limitedLinearV 1;
    div(phi,alpha)  Gauss vanLeer;
    div(phirb,alpha) Gauss linear;
    div(rhoPhi,T)   Gauss limitedLinear 1;
    div(rhoPhi,K)   Gauss limitedLinear 1;
    div(phi,p)      Gauss limitedLinear 1;
    div(phi,k)      Gauss limitedLinear 1;
    div(phi,omega)  Gauss limitedLinear 1;
    div(rhoPhi,k)   Gauss limitedLinear 1;
    div(rhoPhi,omega) Gauss limitedLinear 1;
    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;
    default         Gauss linear;
}

laplacianSchemes
{
    default         Gauss linear corrected;
}

interpolationSchemes
{
    default         linear;
}

snGradSchemes
{
    default         corrected;
}

wallDist
{
    method          meshWave;
}
""")

    _write(case, "system/fvSolution", """solvers
{
    "alpha.water.*"
    {
        nAlphaCorr      2;
        nAlphaSubCycles 1;
        cAlpha          1;
        MULESCorr       yes;
        nLimiterIter    5;
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0;
    }

    "pcorr.*"
    {
        solver          PCG;
        preconditioner  DIC;
        tolerance       1e-5;
        relTol          0;
    }

    p_rgh
    {
        solver          GAMG;
        smoother        DIC;
        tolerance       1e-7;
        relTol          0.01;
    }

    p_rghFinal
    {
        $p_rgh;
        relTol          0;
    }

    "(U|T|k|omega).*"
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-7;
        relTol          0;
        minIter         1;
    }

    "(rho|rhoFinal)"
    {
        solver          diagonal;
    }
}

PIMPLE
{
    momentumPredictor   yes;
    nOuterCorrectors    1;
    nCorrectors         2;
    nNonOrthogonalCorrectors 1;
}

relaxationFactors
{
    equations
    {
        ".*"            1;
    }
}
""")

    _write(case, "system/decomposeParDict", f"""numberOfSubdomains {cfg['n_procs']};

method          scotch;
""")

    # Water below z=0; exhaust pipe stays gas-filled at exhaust temperature
    geo_R = D / 2
    _write(case, "system/setFieldsDict", f"""defaultFieldValues
(
    volScalarFieldValue alpha.water 0
    volScalarFieldValue T {cfg['T_air_C'] + 273.15}
);

regions
(
    boxToCell
    {{
        box (-1e6 -1e6 -1e6) (1e6 1e6 0);
        fieldValues
        (
            volScalarFieldValue alpha.water 1
            volScalarFieldValue T {T_water}
        );
    }}

    cylinderToCell
    {{
        p1 ({-geo['pipe_external_length']} 0 {-Hs});
        p2 ({Lpen} 0 {-Hs});
        radius {geo_R};
        fieldValues
        (
            volScalarFieldValue alpha.water 0
            volScalarFieldValue T {T_exh}
        );
    }}
);
""")


# ─────────────────────────────── mesh helpers ────────────────────────────────

def fix_boundary_types(case: Path) -> None:
    """After gmshToFoam every patch is generic 'patch'; set wall patches to 'wall'."""
    bfile = case / "constant" / "polyMesh" / "boundary"
    text = bfile.read_text(encoding="utf-8", errors="replace")
    for wall in ("pipeWall", "seaBoundary"):
        text = re.sub(
            rf"({wall}\s*\{{[^}}]*?type\s+)patch(\s*;)",
            rf"\g<1>wall\g<2>", text, flags=re.S)
        text = re.sub(
            rf"({wall}\s*\{{[^}}]*?physicalType\s+)patch(\s*;)",
            rf"\g<1>wall\g<2>", text, flags=re.S)
    bfile.write_text(text, encoding="utf-8")


def write_case(case_dir: str | Path, cfg: dict | None = None) -> dict:
    """Write the complete case (fields, constant, system). Returns merged config."""
    case = Path(case_dir)
    if (case / "0").exists():
        shutil.rmtree(case / "0")
    cfg = merged_config(cfg)
    write_fields(case, cfg)
    write_constant(case, cfg)
    write_system(case, cfg)
    (case / "case_config.json").write_text(json.dumps(cfg, indent=2), encoding="utf-8")
    return cfg


def parse_checkmesh(log_text: str) -> dict:
    """Extract headline mesh-quality metrics from a checkMesh log."""
    out = {"ok": "Mesh OK" in log_text, "cells": None, "max_non_ortho": None,
           "avg_non_ortho": None, "max_skewness": None}
    m = re.search(r"^\s*cells:\s*(\d+)", log_text, re.M)
    if m:
        out["cells"] = int(m.group(1))
    m = re.search(r"Mesh non-orthogonality Max:\s*([\d.eE+-]+)\s*average:\s*([\d.eE+-]+)", log_text)
    if m:
        out["max_non_ortho"] = float(m.group(1))
        out["avg_non_ortho"] = float(m.group(2))
    m = re.search(r"Max skewness =\s*([\d.eE+-]+)", log_text)
    if m:
        out["max_skewness"] = float(m.group(1))
    return out
